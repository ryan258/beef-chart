// Also accepts tagged templates. Only catalog text, never inserted values, is translated.
function t(message, ...values) {
  const key = Array.isArray(message) ? message.reduce((s, part, i) => s + (i ? `{${i - 1}}` : '') + part, '') : message;
  const translated = language === 'es-AR' && Object.hasOwn(SPANISH, key) ? SPANISH[key] : key;
  return values.length ? translated.replace(/\{(\d+)\}/g, (_, index) => String(values[index])) : translated;
}
const locale = () => language === 'es-AR' ? 'es-AR' : 'en-US';
// Display rounding only; canonical evidence and calculations retain their values.
function formatNumber(value, options = {}) {
  return typeof value === 'number' && Number.isFinite(value)
    ? value.toLocaleString(locale(), {maximumFractionDigits:6, ...options}) : t('unknown');
}
function currencyTick(value) {
  return `${language === 'es-AR' ? 'US$' : '$'}${formatNumber(value)}`;
}
const originalCopy = new WeakMap();
function translateStaticPage() {
  document.documentElement.lang = language;
  document.title = t('The Cow, Two Ways — Same Animal. Different Perspective.');
  document.querySelectorAll('[data-i18n]').forEach(el => {
    if (!originalCopy.has(el)) originalCopy.set(el, el.innerHTML);
    const original = originalCopy.get(el);
    // These fragments are authored in this file/HTML, never sourced from price records.
    el.innerHTML = language === 'en' ? original : t(original.trim().replace(/\s+/g, ' '));
  });
  for (const attribute of ['aria-label', 'placeholder', 'title', 'alt']) {
    document.querySelectorAll(`[data-i18n-${attribute}]`).forEach(el => {
      el.setAttribute(attribute, t(el.getAttribute(`data-i18n-${attribute}`)));
    });
  }
  document.querySelectorAll('[data-language]').forEach(button => {
    button.setAttribute('aria-pressed', String(button.dataset.language === language));
  });
}
